export type Vars = Record<string, string | number>;

let activeLang: Lang = "zh";

/** Current language for non-React code (date helpers, store toasts). */
export function getActiveLang(): Lang {
  return activeLang;
}

/** Called by the root provider on every render so helpers stay in sync. */
export function setActiveLang(lang: Lang): void {
  activeLang = lang;
}

