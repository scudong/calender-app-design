const REVERSE: Record<string, string> = {};
for (const [en, zh] of Object.entries(DICT)) if (!(zh in REVERSE)) REVERSE[zh] = en;

/** Translate one source string, with optional `{name}` interpolation. */
export function translate(text: string, vars?: Vars, lang: Lang = activeLang): string {
  const out = lang === "zh" ? DICT[text] ?? text : text;
  if (!vars) return out;
  return out.replace(/\{(\w+)\}/g, (raw, key: string) => (key in vars ? String(vars[key]) : raw));
}

/** Active-language shorthand for non-React code. */
export function t(text: string, vars?: Vars, lang?: Lang): string {
  return translate(text, vars, lang);
}

/**
 * Localises demo data by deep-walking strings and swapping entries that match
 * the dictionary exactly. User-typed text never matches and stays untouched.
 * Enum-like fields are skipped so logic keys ("Time off", "approved", …) stay
 * stable while only their labels are translated at render time.
 */
const SKIP_KEYS = new Set([
  "id",
  "type",
  "status",
  "category",
  "kind",
  "color",
  "language",
  "version",
  "workspaceId",
  "requestId",
  "href",
  "date",
  "from",
  "to",
  "start",
  "end",
  "allDay",
  "startedAt",
  "submittedAt",
  "uploadedAt",
  "addedAt",
  "createdAt",
  "startDate",
  "birthday",
  "renewsOn",
  "issueDate",
  "dueDate",
  "currency",
  "minutes",
  "days",
  "billable",
  "enrolled",
  "isDefault",
  "read",
  "budget",
  "used",
  "quantity",
  "rate",
  "size",
  "last4",
]);

export function translateData<T>(value: T, from: Lang, to: Lang): T {
  if (from === to) return value;
  const map = to === "zh" ? DICT : REVERSE;
  const walk = (node: unknown, key?: string): unknown => {
    if (key && SKIP_KEYS.has(key)) return node;
    if (typeof node === "string") return map[node] ?? node;
    if (Array.isArray(node)) return node.map((item) => walk(item));
    if (node && typeof node === "object") {
      const out: Record<string, unknown> = {};
      for (const [k, v] of Object.entries(node)) out[k] = walk(v, k);
      return out;
    }
    return node;
  };
  return walk(value) as T;
}
